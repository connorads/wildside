//! Browser shell for the source port (#19): a thin wasm-bindgen adapter over
//! [`WebSession`]. All rendering/input logic lives in `session.rs` (natively
//! testable); this layer only moves bytes across the JS boundary.
//!
//! The JS side reads the RGBA framebuffer zero-copy via
//! [`frame_ptr`](WildsideGame::frame_ptr)/[`frame_len`](WildsideGame::frame_len)
//! over wasm linear memory, rebuilding its view if memory grows.

mod session;

pub use session::{FRAME_RGB_LEN, FRAME_RGBA_LEN, WebSession};

use sha1::{Digest, Sha1};
use wasm_bindgen::prelude::*;
use wildside_frame::{FRAME_HEIGHT, FRAME_WIDTH};

/// Verify a user-supplied canonical ROM and extract the deterministic runtime
/// bundle. The browser calls this inside its dedicated asset Web Worker.
#[wasm_bindgen]
pub fn extract_runtime_bundle_from_rom(rom: &[u8]) -> Result<Vec<u8>, JsError> {
    let rom = wildside_rom::verify_canonical_rom_bytes(rom)
        .map_err(|error| JsError::new(&error.to_string()))?;
    wildside_data::extract_runtime_bundle(&rom)
        .map_err(|error| JsError::new(&format!("runtime asset extraction failed: {error}")))
}

/// One playable game instance bound to a fetched asset bundle.
#[wasm_bindgen]
pub struct WildsideGame {
    session: WebSession,
}

#[wasm_bindgen]
impl WildsideGame {
    /// Boot from a packed bundle blob (`wildside pack-web-bundle` output).
    /// `undefined` boots the real attract flow (Sega logo → intro → title
    /// menu); a number warps straight into that level (0 = first level).
    #[wasm_bindgen(constructor)]
    pub fn new(bundle: &[u8], level: Option<u8>) -> Result<WildsideGame, JsError> {
        let session = WebSession::from_bundle_blob(bundle, level)
            .map_err(|error| JsError::new(&format!("{error:#}")))?;
        Ok(Self { session })
    }

    /// Advance one frame with the raw controller byte
    /// (Up/Down/Left/Right/B/C/A/Start = bits 0..7).
    pub fn step(&mut self, mask: u8) {
        self.session.step(mask);
    }

    /// Pointer to the RGBA framebuffer in wasm linear memory.
    pub fn frame_ptr(&self) -> *const u8 {
        self.session.rgba_frame().as_ptr()
    }

    /// Byte length of the RGBA framebuffer.
    pub fn frame_len(&self) -> usize {
        self.session.rgba_frame().len()
    }

    /// Enable GEMS audio at the AudioContext sample rate. Browsers refuse
    /// audio before a user gesture, so the shell calls this when it creates
    /// the context, not at boot. Errors if the bundle has no sound banks.
    pub fn enable_audio(&mut self, sample_rate: u32) -> Result<(), JsError> {
        self.session
            .enable_audio(sample_rate)
            .map_err(|error| JsError::new(&format!("{error:#}")))
    }

    /// Pointer to the interleaved-stereo f32 samples generated by the last
    /// `step` in wasm linear memory. Copy before the next `step`.
    pub fn audio_ptr(&self) -> *const f32 {
        self.session.audio_samples().as_ptr()
    }

    /// f32 count of the last `step`'s samples (2 × stereo frames; varies by
    /// one pair between frames when the device rate is not a multiple of 60).
    pub fn audio_len(&self) -> usize {
        self.session.audio_samples().len()
    }

    /// SHA-1 of the current RGB24 frame — matches a hash of the raw pixel data
    /// in a native `capture-frames` PNG for the same scenario frame, so parity
    /// is checkable from the browser console without downloading the buffer.
    pub fn frame_rgb_sha1(&self) -> String {
        let mut hasher = Sha1::new();
        hasher.update(self.session.rgb_frame());
        format!("{:x}", hasher.finalize())
    }

    /// Whether the engine is on a VDP shell screen (Sega/intro/title/level
    /// card). Level cards hold until a button edge, so the JS shell can hint.
    pub fn on_shell_screen(&self) -> bool {
        self.session.on_shell_screen()
    }

    /// Diagnostic snapshot for the browser console (game mode, level, render
    /// branch); throwaway aid while the shell is young.
    pub fn debug_state(&self) -> String {
        self.session.debug_state()
    }

    pub fn width() -> u32 {
        FRAME_WIDTH
    }

    pub fn height() -> u32 {
        FRAME_HEIGHT
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    use wildside_data::{manifest_path, pack_bundle_blob};

    fn repo_root() -> PathBuf {
        match std::env::var("KID_REPO_ROOT") {
            Ok(root) if !root.is_empty() => PathBuf::from(root),
            _ => PathBuf::from(env!("CARGO_MANIFEST_DIR"))
                .parent()
                .and_then(std::path::Path::parent)
                .expect("wildside-web crate should live under <repo>/crates/wildside-web")
                .to_path_buf(),
        }
    }

    fn cached_bundle_root() -> Option<PathBuf> {
        let generated = repo_root().join(".cache/generated");
        for entry in std::fs::read_dir(generated).ok()?.flatten() {
            let path = entry.path();
            if manifest_path(&path).is_file() {
                return Some(path);
            }
        }
        eprintln!(
            "skipping cache-backed wasm boundary test: no generated bundle in .cache/generated"
        );
        None
    }

    fn cached_bundle_blob() -> Option<Vec<u8>> {
        Some(pack_bundle_blob(&cached_bundle_root()?).expect("pack cached web bundle"))
    }

    fn cached_game(level: Option<u8>) -> Option<WildsideGame> {
        let blob = cached_bundle_blob()?;
        Some(WildsideGame::new(&blob, level).expect("cached WildsideGame"))
    }

    #[test]
    fn wasm_boundary_reports_frame_buffer_contract() {
        let Some(mut game) = cached_game(Some(0)) else {
            return;
        };

        assert_eq!(WildsideGame::width(), FRAME_WIDTH);
        assert_eq!(WildsideGame::height(), FRAME_HEIGHT);
        assert_eq!(game.frame_len(), FRAME_RGBA_LEN);
        assert_eq!(game.frame_ptr(), game.session.rgba_frame().as_ptr());
        assert!(!game.frame_ptr().is_null());

        for _ in 0..120 {
            if !game.on_shell_screen() {
                break;
            }
            game.step(0);
        }
        assert!(
            !game.on_shell_screen(),
            "ASM Load_InGame (kid.asm:23623-23629) should become visible through the wasm boundary step call"
        );
        let trace_before_input = game.session.trace().clone();
        for _ in 0..8 {
            game.step(0x08);
        }
        assert_ne!(
            game.session.trace(),
            &trace_before_input,
            "stepping through the wasm boundary should advance the underlying trace"
        );
        assert_eq!(game.frame_len(), FRAME_RGBA_LEN);
        assert_eq!(game.frame_ptr(), game.session.rgba_frame().as_ptr());
    }

    #[test]
    fn wasm_extractor_boundary_matches_native_runtime_bundle() {
        let Some(root) = cached_bundle_root() else {
            return;
        };
        let rom_path = repo_root().join(".cache/upstream/kid-chameleon-disasm/kid.bin");
        let Ok(rom) = std::fs::read(rom_path) else {
            return;
        };

        assert_eq!(
            extract_runtime_bundle_from_rom(&rom).expect("extract canonical ROM"),
            wildside_data::pack_runtime_bundle_blob(&root).expect("pack runtime bundle")
        );
    }

    #[test]
    fn wasm_boundary_exposes_audio_samples_after_enablement() {
        let Some(mut game) = cached_game(Some(0)) else {
            return;
        };

        if let Err(err) = game.enable_audio(48_000) {
            eprintln!("skipping cache-backed wasm audio boundary test: {err:?}");
            return;
        }
        assert_eq!(game.audio_len(), 0);

        game.step(0);

        assert_eq!(
            game.audio_len(),
            800 * 2,
            "ASM Load_InGame (kid.asm:23623-23629) should expose one 48kHz 60Hz stereo audio frame through the wasm boundary"
        );
        assert_eq!(game.audio_ptr(), game.session.audio_samples().as_ptr());
        assert!(!game.audio_ptr().is_null());
    }

    #[test]
    fn wasm_boundary_reports_hash_shell_and_debug_state() {
        let Some(shell_game) = cached_game(None) else {
            return;
        };
        let Some(mut gameplay_game) = cached_game(Some(0)) else {
            return;
        };
        for _ in 0..120 {
            if !gameplay_game.on_shell_screen() {
                break;
            }
            gameplay_game.step(0);
        }

        let mut hasher = Sha1::new();
        hasher.update(shell_game.session.rgb_frame());
        assert_eq!(
            shell_game.frame_rgb_sha1(),
            format!("{:x}", hasher.finalize())
        );
        assert_eq!(
            shell_game.frame_rgb_sha1().len(),
            40,
            "browser console parity hashes should be full SHA-1 hex strings"
        );
        assert!(
            shell_game.on_shell_screen(),
            "ASM Load_SegaScreen starts as a VDP shell screen"
        );
        assert!(
            !gameplay_game.on_shell_screen(),
            "ASM Load_InGame should eventually expose gameplay rendering through the wasm boundary"
        );

        let debug = shell_game.debug_state();
        assert!(
            debug.contains("mode=SegaScreen")
                && debug.contains("level=0x00")
                && debug.contains("vdp=true")
                && debug.contains("grid=true")
                && debug.contains("rgb_nonzero="),
            "debug_state should cross the wasm boundary unchanged"
        );
    }
}
